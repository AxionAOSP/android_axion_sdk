package com.android.server.axdragonite

import java.io.File

object AxCmdTable {
    const val CPUSET_DIR = "/dev/cpuset"
    const val CPUCTL_DIR = "/dev/cpuctl"
    const val FILE_CGROUP_PROCS = "cgroup.procs"
    const val FILE_TASKS = "tasks"
    const val FILE_CPUS = "cpus"
    const val FILE_CPU_SHARES = "cpu.shares"
    const val FILE_UCLAMP_MIN = "cpu.uclamp.min"
    const val FILE_UCLAMP_MAX = "cpu.uclamp.max"
    const val PATH_SEP = "/"
    const val GROUP_TOP_APP = "top-app"
    const val GROUP_FOREGROUND = "foreground"
    const val GROUP_BACKGROUND = "background"
    const val GROUP_SYSTEM_BACKGROUND = "system-background"
    const val GROUP_RESTRICTED = "restricted"
    const val GROUP_DEX2OAT = "dex2oat"
    const val GROUP_CAMERA_DAEMON = "camera-daemon"
    const val GROUP_SYSTEM = "system"
    const val GROUP_RT = "rt"
    const val GROUP_AX_FOREGROUND = "ax_foreground"
    const val GROUP_FOREGROUND_WINDOW = "foreground_window"

    enum class Type(val dir: String?, val file: String?) {
        CPUSET_PROCS(CPUSET_DIR, FILE_CGROUP_PROCS),
        CPUSET_TASKS(CPUSET_DIR, FILE_TASKS),
        CPUSET_CPUS(CPUSET_DIR, FILE_CPUS),
        CPUCTL_PROCS(CPUCTL_DIR, FILE_CGROUP_PROCS),
        CPUCTL_SHARES(CPUCTL_DIR, FILE_CPU_SHARES),
        CPUCTL_UCLAMP_MIN(CPUCTL_DIR, FILE_UCLAMP_MIN),
        CPUCTL_UCLAMP_MAX(CPUCTL_DIR, FILE_UCLAMP_MAX),
        FUNCTION(null, null),
    }

    enum class Command(val id: Int, val type: Type = Type.FUNCTION, group: String? = null) {
        CMD_CPUSET_TA_PROCS(100, Type.CPUSET_PROCS, GROUP_TOP_APP),
        CMD_CPUSET_FG_PROCS(101, Type.CPUSET_PROCS, GROUP_FOREGROUND),
        CMD_CPUSET_BG_PROCS(102, Type.CPUSET_PROCS, GROUP_BACKGROUND),
        CMD_CPUSET_SBG_PROCS(103, Type.CPUSET_PROCS, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUSET_CAMERA_DAEMON_PROCS(104, Type.CPUSET_PROCS, GROUP_CAMERA_DAEMON),
        CMD_CPUSET_RESTRICTED_PROCS(105, Type.CPUSET_PROCS, GROUP_RESTRICTED),
        CMD_CPUSET_DEX2OAT_PROCS(106, Type.CPUSET_PROCS, GROUP_DEX2OAT),
        CMD_CPUSET_TA_TASKS(150, Type.CPUSET_TASKS, GROUP_TOP_APP),
        CMD_CPUSET_FG_TASKS(151, Type.CPUSET_TASKS, GROUP_FOREGROUND),
        CMD_CPUSET_BG_TASKS(152, Type.CPUSET_TASKS, GROUP_BACKGROUND),
        CMD_CPUSET_SBG_TASKS(153, Type.CPUSET_TASKS, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUSET_CAMERA_DAEMON_TASKS(154, Type.CPUSET_TASKS, GROUP_CAMERA_DAEMON),
        CMD_CPUSET_RESTRICTED_TASKS(155, Type.CPUSET_TASKS, GROUP_RESTRICTED),
        CMD_CPUSET_DEX2OAT_TASKS(156, Type.CPUSET_TASKS, GROUP_DEX2OAT),
        CMD_CPUSET_TA_CPUS(200, Type.CPUSET_CPUS, GROUP_TOP_APP),
        CMD_CPUSET_FG_CPUS(201, Type.CPUSET_CPUS, GROUP_FOREGROUND),
        CMD_CPUSET_BG_CPUS(202, Type.CPUSET_CPUS, GROUP_BACKGROUND),
        CMD_CPUSET_SBG_CPUS(203, Type.CPUSET_CPUS, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUSET_CAMERA_DAEMON_CPUS(204, Type.CPUSET_CPUS, GROUP_CAMERA_DAEMON),
        CMD_CPUSET_RESTRICTED_CPUS(205, Type.CPUSET_CPUS, GROUP_RESTRICTED),
        CMD_CPUSET_DEX2OAT_CPUS(206, Type.CPUSET_CPUS, GROUP_DEX2OAT),
        CMD_CPUCTL_SYS_PROCS(300, Type.CPUCTL_PROCS, GROUP_SYSTEM),
        CMD_CPUCTL_SBG_PROCS(301, Type.CPUCTL_PROCS, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUCTL_TA_PROCS(302, Type.CPUCTL_PROCS, GROUP_TOP_APP),
        CMD_CPUCTL_DEX_PROCS(303, Type.CPUCTL_PROCS, GROUP_DEX2OAT),
        CMD_CPUCTL_FG_PROCS(304, Type.CPUCTL_PROCS, GROUP_FOREGROUND),
        CMD_CPUCTL_RT_PROCS(305, Type.CPUCTL_PROCS, GROUP_RT),
        CMD_CPUCTL_BG_PROCS(306, Type.CPUCTL_PROCS, GROUP_BACKGROUND),
        CMD_CPUCTL_RESTRICTED_PROCS(307, Type.CPUCTL_PROCS, GROUP_RESTRICTED),
        CMD_CPUCTL_ROOT_PROCS(308, Type.CPUCTL_PROCS),
        CMD_CPUCTL_SYS_UCLAMP_MIN(400, Type.CPUCTL_UCLAMP_MIN, GROUP_SYSTEM),
        CMD_CPUCTL_SYS_UCLAMP_MAX(401, Type.CPUCTL_UCLAMP_MAX, GROUP_SYSTEM),
        CMD_CPUCTL_SBG_UCLAMP_MIN(402, Type.CPUCTL_UCLAMP_MIN, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUCTL_SBG_UCLAMP_MAX(403, Type.CPUCTL_UCLAMP_MAX, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUCTL_TA_UCLAMP_MIN(404, Type.CPUCTL_UCLAMP_MIN, GROUP_TOP_APP),
        CMD_CPUCTL_TA_UCLAMP_MAX(405, Type.CPUCTL_UCLAMP_MAX, GROUP_TOP_APP),
        CMD_CPUCTL_DEX_UCLAMP_MIN(406, Type.CPUCTL_UCLAMP_MIN, GROUP_DEX2OAT),
        CMD_CPUCTL_DEX_UCLAMP_MAX(407, Type.CPUCTL_UCLAMP_MAX, GROUP_DEX2OAT),
        CMD_CPUCTL_FG_UCLAMP_MIN(408, Type.CPUCTL_UCLAMP_MIN, GROUP_FOREGROUND),
        CMD_CPUCTL_FG_UCLAMP_MAX(409, Type.CPUCTL_UCLAMP_MAX, GROUP_FOREGROUND),
        CMD_CPUCTL_RT_UCLAMP_MIN(410, Type.CPUCTL_UCLAMP_MIN, GROUP_RT),
        CMD_CPUCTL_RT_UCLAMP_MAX(411, Type.CPUCTL_UCLAMP_MAX, GROUP_RT),
        CMD_CPUCTL_BG_UCLAMP_MIN(412, Type.CPUCTL_UCLAMP_MIN, GROUP_BACKGROUND),
        CMD_CPUCTL_BG_UCLAMP_MAX(413, Type.CPUCTL_UCLAMP_MAX, GROUP_BACKGROUND),
        CMD_CPUCTL_RESTRICTED_UCLAMP_MIN(414, Type.CPUCTL_UCLAMP_MIN, GROUP_RESTRICTED),
        CMD_CPUCTL_RESTRICTED_UCLAMP_MAX(415, Type.CPUCTL_UCLAMP_MAX, GROUP_RESTRICTED),
        CMD_CPUCTL_SYS_CPU_SHARES(440, Type.CPUCTL_SHARES, GROUP_SYSTEM),
        CMD_CPUCTL_SBG_CPU_SHARES(441, Type.CPUCTL_SHARES, GROUP_SYSTEM_BACKGROUND),
        CMD_CPUCTL_TA_CPU_SHARES(442, Type.CPUCTL_SHARES, GROUP_TOP_APP),
        CMD_CPUCTL_DEX_CPU_SHARES(443, Type.CPUCTL_SHARES, GROUP_DEX2OAT),
        CMD_CPUCTL_FG_CPU_SHARES(444, Type.CPUCTL_SHARES, GROUP_FOREGROUND),
        CMD_CPUCTL_RT_CPU_SHARES(445, Type.CPUCTL_SHARES, GROUP_RT),
        CMD_CPUCTL_BG_CPU_SHARES(446, Type.CPUCTL_SHARES, GROUP_BACKGROUND),
        CMD_CPUCTL_RESTRICTED_CPU_SHARES(447, Type.CPUCTL_SHARES, GROUP_RESTRICTED),
        CMD_CPUCTL_AXFG_CPU_SHARES(450, Type.CPUCTL_SHARES, GROUP_AX_FOREGROUND),
        CMD_CPUCTL_FW_CPU_SHARES(451, Type.CPUCTL_SHARES, GROUP_FOREGROUND_WINDOW),
        CMD_ANIMATION_BOOST(500),
        CMD_THREAD_BOOST(501),
        CMD_THREAD_AFFINITY(600),
        CMD_PROCESS_AFFINITY(601),
        CMD_AX_NAMED_THREAD_AFFINITY(602),
        CMD_KSWAPD_CONTROLL_AFFINITY(603),
        CMD_BACKGROUND_FREEZE(700),
        CMD_BACKGROUND_LOAD_LIMIT(800),
        CMD_PLATFORM_CONTROL(900),
        CMD_SF_CONTROL_AFFINITY(1000);

        val pathFile: File? =
            type.dir?.let { File(listOfNotNull(it, group, type.file).joinToString(PATH_SEP)) }
    }

    fun cmdOf(type: Type): List<Command> = Command.entries.filter { it.type == type }
}
